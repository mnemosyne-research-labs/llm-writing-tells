"""Render the confirmatory result CSVs as Markdown tables for results.md."""

import argparse
import math
from pathlib import Path

import polars as pl

from llm_tells.analysis import PRIMARY, SECONDARY

LABELS = {t.id: t.label for t in PRIMARY + SECONDARY} | {
    "S9a": "Content: generic, no specifics (coder A)",
    "S9b": "Content: hype (coder A)",
}


def fmt(value: float | None, digits: int = 2) -> str:
    """Format a number for a table.

    Args:
        value: Number or None
        digits: Decimal places

    Returns:
        The formatted number, "∞" for infinity or "\u2013" when missing
    """
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "\u2013"
    if math.isinf(value):
        return "∞"
    return f"{value:.{digits}f}"


def pct(value: float | None) -> str:
    """Format a share as a percentage.

    Args:
        value: Share between 0 and 1

    Returns:
        The percentage
    """
    return "\u2013" if value is None or math.isnan(value) else f"{100 * value:.1f}%"


def p_value(value: float) -> str:
    """Format a p-value.

    Args:
        value: p-value

    Returns:
        The formatted p-value
    """
    return "< 0.001" if value < 0.001 else f"{value:.3f}"


def family_table(frame: pl.DataFrame, adjusted: str) -> str:
    """Primary or secondary verdict table.

    Args:
        frame: primary.csv or secondary.csv
        adjusted: Column header for the adjusted p-value

    Returns:
        Markdown table
    """
    lines = [
        f"| Tell | Measure | Effect (95% CI) | 90% CI | {adjusted} | Human share | Model share | LR+ (95% CI) | Verdict |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in frame.iter_rows(named=True):
        effect_name = "d" if row["measure"] == "cv" else "ratio"
        lines.append(
            f"| {row['id']} {LABELS.get(row['id'], row['label'])} | {row['measure']} | {effect_name} {fmt(row['effect'])} "
            f"({fmt(row['ci95_lo'])}\u2013{fmt(row['ci95_hi'])}) | {fmt(row['ci90_lo'])}\u2013{fmt(row['ci90_hi'])} | "
            f"{p_value(row['p_adj'])} | {pct(row['fpr'])} | {pct(row['hit'])} | {fmt(row['lr'], 1)} "
            f"({fmt(row['lr_lo'], 1)}\u2013{fmt(row['lr_hi'], 1)}) | {row['verdict']} |"
        )
    return "\n".join(lines)


def per_model_table(frame: pl.DataFrame) -> str:
    """Per-model and per-register ratios, one row per tell.

    Args:
        frame: per_model_register.csv

    Returns:
        Markdown table
    """
    cells = sorted({(r["register"], r["model"]) for r in frame.iter_rows(named=True)})
    header = "| Tell | " + " | ".join(f"{m} {r.upper()}" for r, m in cells) + " |"
    lines = [header, "| --- |" + " --- |" * len(cells)]
    for tell_id in frame["id"].unique(maintain_order=True):
        sub = {
            (r["register"], r["model"]): r
            for r in frame.filter(pl.col("id") == tell_id).iter_rows(named=True)
        }
        values: list[str] = []
        for cell in cells:
            row = sub.get(cell)
            values.append(
                "\u2013"
                if row is None
                else f"{fmt(row['effect'])} ({fmt(row['ci95_lo'])}\u2013{fmt(row['ci95_hi'])})"
            )
        lines.append(f"| {tell_id} | " + " | ".join(values) + " |")
    return "\n".join(lines)


def main() -> None:
    """Write results_tables.md next to the CSVs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results_dir", type=Path)
    args = parser.parse_args()
    out = [
        "# Result tables (generated by `llm_tells.summarize`)",
        "",
        "Effect: average model-to-human ratio (rate or presence), or for P10 the standardized difference d. Human share is the false-positive rate (texts with at least one occurrence); model share is the hit rate averaged over models and registers.",
        "",
        "## Primary (Holm)",
        "",
        family_table(pl.read_csv(args.results_dir / "primary.csv"), "Holm p"),
        "",
        "## Secondary (BH)",
        "",
        family_table(pl.read_csv(args.results_dir / "secondary.csv"), "BH q"),
        "",
        "## Per model and register (ratio, 95% CI)",
        "",
        per_model_table(pl.read_csv(args.results_dir / "per_model_register.csv")),
        "",
    ]
    (args.results_dir / "results_tables.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
